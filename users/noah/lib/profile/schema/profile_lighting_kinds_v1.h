// ─── Parameter layouts ──────────────────────────────────────────────────────
//
// A layout packs up to four parameter types in five-bit fields, first
// parameter in the low field. The validator checks every parameter from its type; a
// kind has no validation code of its own.

typedef enum {
    NOAH_LIGHTING_PARAM_END = 0u,
    NOAH_LIGHTING_PARAM_LAYER_SELECTOR,
    NOAH_LIGHTING_PARAM_MODE_SELECTOR,
    NOAH_LIGHTING_PARAM_COMBO_ROLE,
    NOAH_LIGHTING_PARAM_BEHAVIOUR_STATES,
    NOAH_LIGHTING_PARAM_BEHAVIOUR_SCOPE,
    NOAH_LIGHTING_PARAM_KEY_SET,
    NOAH_LIGHTING_PARAM_PALETTE_INDEX,
    NOAH_LIGHTING_PARAM_MAP,
    NOAH_LIGHTING_PARAM_LEVEL,
    NOAH_LIGHTING_PARAM_MILLISECONDS,
    NOAH_LIGHTING_PARAM_THING_SELECTOR,
    NOAH_LIGHTING_PARAM_LAYER_STATUS,
    NOAH_LIGHTING_PARAM_MODE_STATUS,
    NOAH_LIGHTING_PARAM_BEHAVIOUR_PHASE,
    NOAH_LIGHTING_PARAM_TAP_SELECTOR,
    NOAH_LIGHTING_PARAM_KEY_SELECTOR,
    NOAH_LIGHTING_PARAM_MODIFIER,
    NOAH_LIGHTING_PARAM_SIDE,
    NOAH_LIGHTING_PARAM_MODIFIER_STATE,
    NOAH_LIGHTING_PARAM_HOST_LOCK,
    NOAH_LIGHTING_PARAM_POINTER_STATE,
    NOAH_LIGHTING_PARAM_KEY_QUERY,

} noah_lighting_param_type_t;

#define NOAH_LIGHTING_PARAMS0 0u
#define NOAH_LIGHTING_PARAMS1(a) ((uint32_t)(NOAH_LIGHTING_PARAM_##a))
#define NOAH_LIGHTING_PARAMS2(a, b) ((uint32_t)(NOAH_LIGHTING_PARAM_##a | (NOAH_LIGHTING_PARAM_##b << 5u)))

#define NOAH_LIGHTING_PARAMS3(a, b, c) (NOAH_LIGHTING_PARAMS2(a, b) | ((uint32_t)NOAH_LIGHTING_PARAM_##c << 10u))

static inline uint8_t noah_lighting_param_size(uint8_t type) {
    return type == NOAH_LIGHTING_PARAM_MILLISECONDS ? 2u : (type == NOAH_LIGHTING_PARAM_END ? 0u : 1u);
}

static inline uint8_t noah_lighting_param_layout_length(uint32_t layout) {
    uint8_t length = 0u;
    for (; layout != 0u; layout >>= 5u) {
        length = (uint8_t)(length + noah_lighting_param_size((uint8_t)(layout & 0x1fu)));
    }
    return length;
}

