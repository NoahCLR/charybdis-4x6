// ─── Parameter layouts ──────────────────────────────────────────────────────
//
// A layout packs up to four parameter types, four bits each, first parameter
// in the low nibble. The validator checks every parameter from its type; a
// kind has no validation code of its own.

typedef enum {
    NOAH_LIGHTING_PARAM_END = 0u,
    NOAH_LIGHTING_PARAM_LAYER_SELECTOR,
    NOAH_LIGHTING_PARAM_MODE_SELECTOR,
    NOAH_LIGHTING_PARAM_COMBO_ROLE,
    NOAH_LIGHTING_PARAM_BEHAVIOUR_STATES,
    NOAH_LIGHTING_PARAM_BEHAVIOUR_SCOPE,
    NOAH_LIGHTING_PARAM_KEY_SET,
    NOAH_LIGHTING_PARAM_PALETTE_INDEX,
    NOAH_LIGHTING_PARAM_MAP,
    NOAH_LIGHTING_PARAM_LEVEL,
    NOAH_LIGHTING_PARAM_MILLISECONDS,
    NOAH_LIGHTING_PARAM_THING_SELECTOR,
} noah_lighting_param_type_t;

#define NOAH_LIGHTING_PARAMS0 0u
#define NOAH_LIGHTING_PARAMS1(a) ((uint16_t)(NOAH_LIGHTING_PARAM_##a))
#define NOAH_LIGHTING_PARAMS2(a, b) ((uint16_t)(NOAH_LIGHTING_PARAM_##a | (NOAH_LIGHTING_PARAM_##b << 4u)))

static inline uint8_t noah_lighting_param_size(uint8_t type) {
    return type == NOAH_LIGHTING_PARAM_MILLISECONDS ? 2u : (type == NOAH_LIGHTING_PARAM_END ? 0u : 1u);
}

static inline uint8_t noah_lighting_param_layout_length(uint16_t layout) {
    uint8_t length = 0u;
    for (; layout != 0u; layout >>= 4u) {
        length = (uint8_t)(length + noah_lighting_param_size((uint8_t)(layout & 0x0fu)));
    }
    return length;
}

