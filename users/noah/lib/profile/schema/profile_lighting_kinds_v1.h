// ─── Compiled support masks ─────────────────────────────────────────────────
//
// Version-5 ids are below 32, so one word per registry reports them. A later
// id at 32 or above widens these masks, not the format.

#define NOAH_LIGHTING_FACT_BIT(id, name, thing, layout) | (UINT32_C(1) << (id))
#define NOAH_LIGHTING_TARGET_BIT(id, name, layout, place) | (UINT32_C(1) << (id))
#define NOAH_LIGHTING_PLACE_BIT(id, name, layout, place) | ((place) ? (UINT32_C(1) << (id)) : 0u)
#define NOAH_LIGHTING_PAINT_BIT(id, name, layout, below, timed) | (UINT32_C(1) << (id))
#define NOAH_LIGHTING_TIMING_BIT(id, name, layout, timed) | (UINT32_C(1) << (id))
#define NOAH_LIGHTING_EXTENSION_BIT(id, name, length) | (UINT32_C(1) << (id))

#define NOAH_LIGHTING_COMPILED_FACTS (0u NOAH_LIGHTING_FACT_ROWS(NOAH_LIGHTING_FACT_BIT))
#define NOAH_LIGHTING_COMPILED_TARGETS (0u NOAH_LIGHTING_TARGET_ROWS(NOAH_LIGHTING_TARGET_BIT))
#define NOAH_LIGHTING_COMPILED_PLACES (0u NOAH_LIGHTING_TARGET_ROWS(NOAH_LIGHTING_PLACE_BIT))
#define NOAH_LIGHTING_COMPILED_PAINTS (0u NOAH_LIGHTING_PAINT_ROWS(NOAH_LIGHTING_PAINT_BIT))
#define NOAH_LIGHTING_COMPILED_TIMINGS (0u NOAH_LIGHTING_TIMING_ROWS(NOAH_LIGHTING_TIMING_BIT))
#define NOAH_LIGHTING_COMPILED_RULE_EXTENSIONS 0u
#define NOAH_LIGHTING_COMPILED_DOMAIN_EXTENSIONS (0u NOAH_LIGHTING_DOMAIN_EXTENSION_ROWS(NOAH_LIGHTING_EXTENSION_BIT))
#define NOAH_LIGHTING_COMPILED_THINGS ((NOAH_LIGHTING_THING_LAYER_ON ? (1u << NOAH_LIGHTING_THING_LAYER) : 0u) | (NOAH_LIGHTING_THING_POINTING_MODE_ON ? (1u << NOAH_LIGHTING_THING_POINTING_MODE) : 0u) | (NOAH_LIGHTING_THING_COMBO_ON ? (1u << NOAH_LIGHTING_THING_COMBO) : 0u) | (NOAH_LIGHTING_THING_BEHAVIOUR_ON ? (1u << NOAH_LIGHTING_THING_BEHAVIOUR) : 0u))
