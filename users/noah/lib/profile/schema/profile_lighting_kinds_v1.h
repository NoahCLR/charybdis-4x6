// ─── Compiled support masks ─────────────────────────────────────────────────
//
// Version-5 ids are below 32, so one word per registry reports them. A later
// id at 32 or above widens these masks, not the format.

#define NOAH_LIGHTING_FACT_BIT(id, name, thing, layout, slots, selector, signatures, live, role) | (UINT32_C(1) << (id))
#define NOAH_LIGHTING_TARGET_BIT(id, name, layout, place) | (UINT32_C(1) << (id))
#define NOAH_LIGHTING_PLACE_BIT(id, name, layout, place) | ((place) ? (UINT32_C(1) << (id)) : 0u)
#define NOAH_LIGHTING_PAINT_BIT(id, name, layout, below, timed) | (UINT32_C(1) << (id))
#define NOAH_LIGHTING_TIMING_BIT(id, name, layout, timed, role) | (UINT32_C(1) << (id))
#define NOAH_LIGHTING_EXTENSION_BIT(id, name, length) | (UINT32_C(1) << (id))

